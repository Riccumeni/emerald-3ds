"""Convert the supplied UI reference to lossless RGB565 runs for the 3DS.

The artwork stays unchanged. Live text, cursor and counters are drawn by C.
Run from any directory; the generated header is checked in for normal builds.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / "assets/artwork/pokedex/reference.png"
target = root / "include/3ds_pokedex_skin.h"
image = Image.open(source).convert("RGB").resize((320, 240), Image.Resampling.NEAREST)
pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in image.getdata()]
runs = []
for colour in pixels:
    if runs and runs[-1][1] == colour and runs[-1][0] < 65535:
        runs[-1][0] += 1
    else:
        runs.append([1, colour])
with target.open("w", encoding="utf-8", newline="\n") as out:
    out.write("/* Generated by scripts/gen_pokedex_skin.py from the supplied reference. */\n")
    out.write("static const u16 sPokedexSkinRuns[][2] = {\n")
    for start in range(0, len(runs), 8):
        out.write("    " + ", ".join("{%d, 0x%04x}" % tuple(run) for run in runs[start:start + 8]) + ",\n")
    out.write("};\n")
print(f"Pokédex skin: {len(runs)} runs, {len(pixels)} pixels -> {target}")
